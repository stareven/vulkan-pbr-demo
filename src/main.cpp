#include "pbr_app.h"

#include <iostream>

// ============================================================================
// 程序入口 - 创建并运行 PBR 渲染应用
// ============================================================================
// main 函数是 C++ 程序的入口点:
//   1. 创建 PBRApp 实例, 传入命令行参数 (argc/argv)
//   2. 调用 app.run() 启动主循环
//   3. 捕获并打印异常, 返回错误码
//
// 异常处理:
//   - Vulkan API 调用失败会抛 std::runtime_error
//   - 文件加载失败 (shader/纹理) 也会抛异常
//   - 这里统一捕获并打印错误信息, 避免程序崩溃时无提示
//
// 返回值:
//   - 0: 正常退出
//   - 1: 发生异常, 错误退出
// ============================================================================
int main(int argc, char* argv[]) {
    PBRApp app(argc, argv);
    try {
        app.run();
    } catch (const std::exception& e) {
        std::cerr << "ERROR: " << e.what() << "\n";
        return 1;
    }
    return 0;
}
