#include "mesh.h"
#include <cmath>

// ============================================================================
// 生成球体顶点
// ============================================================================
// 算法:
//   - 用球坐标 (phi, theta) 遍历球面
//   - phi: 纬度角, 从 0 (北极) 到 π (南极)
//   - theta: 经度角, 从 0 到 2π
//   - 球坐标转直角坐标:
//       x = sin(phi) * cos(theta)
//       y = cos(phi)
//       z = sin(phi) * sin(theta)
//   - 对于单位球, 位置向量就是法向量 (归一化后相同)
//   - UV 坐标: u = theta/(2π), v = phi/π
//
// 参数:
//   - rings: 纬度方向细分 (32 = 32 圈)
//   - sectors: 经度方向细分 (64 = 64 条经线)
//   - 总顶点数: (rings+1) * (sectors+1)
//
// 注意:
//   - 顶点有重复 (经度 0 和 2π 是同一个位置但 UV 不同)
//   - 这是为了正确处理纹理接缝
// ============================================================================
std::vector<Vertex> generateSphere(int rings, int sectors) {
    std::vector<Vertex> verts;
    const float R = 1.0f;  // 球体半径
    // 遍历纬度 (从北极到南极)
    for (int r = 0; r <= rings; ++r) {
        float phi = M_PI * float(r) / rings;  // phi: 0 -> π
        // 遍历经度 (绕一圈)
        for (int s = 0; s <= sectors; ++s) {
            float theta = 2.0f * M_PI * float(s) / sectors;  // theta: 0 -> 2π
            // 球坐标转直角坐标
            float x = std::sin(phi) * std::cos(theta);
            float y = std::cos(phi);
            float z = std::sin(phi) * std::sin(theta);
            Vec3 p{x * R, y * R, z * R};  // 位置
            Vec3 n = p.normalize();        // 法向量 (单位球 = 位置向量归一化)
            Vec2 uv{float(s) / sectors, float(r) / rings};  // UV 坐标
            verts.push_back({p, n, uv});
        }
    }
    return verts;
}

// ============================================================================
// 生成球体索引
// ============================================================================
// 算法:
//   - 遍历每个四边形网格 (由 4 个顶点组成)
//   - 把每个四边形拆成 2 个三角形 (6 个索引)
//   - 顶点索引计算:
//       a = 当前行的第 s 个顶点
//       b = 下一行的第 s 个顶点
//       三角形 1: a, b, a+1
//       三角形 2: a+1, b, b+1
//
// 参数:
//   - rings/sectors: 必须与 generateSphere 的参数一致
//
// 返回:
//   - 索引数组, 每 3 个索引组成一个三角形
//   - 总索引数: rings * sectors * 6
// ============================================================================
std::vector<uint32_t> generateSphereIndices(int rings, int sectors) {
    std::vector<uint32_t> idx;
    for (int r = 0; r < rings; ++r) {
        for (int s = 0; s < sectors; ++s) {
            // 计算四个顶点的索引
            uint32_t a = r * (sectors + 1) + s;          // 当前行当前列
            uint32_t b = a + sectors + 1;                // 下一行当前列
            // 三角形 1: 左下/右下/左上
            idx.push_back(a);
            idx.push_back(b);
            idx.push_back(a + 1);
            // 三角形 2: 左上/右下/右上
            idx.push_back(a + 1);
            idx.push_back(b);
            idx.push_back(b + 1);
        }
    }
    return idx;
}

// ============================================================================
// 生成地面平面
// ============================================================================
// 用途:
//   - 作为地面接收阴影, 展示阴影贴图效果
//   - 简单的四边形 (2 个三角形, 6 个顶点)
//
// 参数:
//   - size: 平面边长 (默认 10.0, 覆盖较大区域)
//   - y: 平面高度 (默认 -1.5, 在球体下方)
//
// 顶点布局:
//   - 4 个角点 + 2 个重复点 (组成 2 个三角形)
//   - 法向量: (0, 1, 0), 朝上 (Y 轴正方向)
//   - UV: (0,0) 到 (1,1), 可用于地面贴图
//
// 注意:
//   - 这里用 6 个顶点 (有重复), 也可以用 4 个顶点 + 索引
//   - 重复顶点是为了简化索引生成
// ============================================================================
std::vector<Vertex> generatePlane(float size, float y) {
    float h = size * 0.5f;  // 半边长
    return {
        {{-h, y, -h}, {0, 1, 0}, {0, 0}},  // 左下
        {{ h, y, -h}, {0, 1, 0}, {1, 0}},  // 右下
        {{ h, y,  h}, {0, 1, 0}, {1, 1}},  // 右上
        {{-h, y, -h}, {0, 1, 0}, {0, 0}},  // 左下 (重复, 第二个三角形)
        {{ h, y,  h}, {0, 1, 0}, {1, 1}},  // 右上 (重复)
        {{-h, y,  h}, {0, 1, 0}, {0, 1}},  // 左上
    };
}

// ============================================================================
// 生成平面索引
// ============================================================================
// 返回:
//   - {0, 1, 2, 3, 4, 5}: 6 个索引, 对应 2 个三角形
//   - 三角形 1: 顶点 0, 1, 2
//   - 三角形 2: 顶点 3, 4, 5
// ============================================================================
std::vector<uint32_t> generatePlaneIndices() {
    return {0, 1, 2, 3, 4, 5};
}
