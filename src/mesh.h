#pragma once

#include "types.h"
#include <vector>

// ============================================================================
// 网格生成函数
// ============================================================================
// 这些函数生成基本的 3D 几何体 (球体/平面), 返回顶点数组和索引数组:
//   - 顶点包含位置/法向量/纹理坐标
//   - 索引用于索引绘制 (减少重复顶点)
//
// 生成的数据后续会上传到 GPU 的顶点缓冲/索引缓冲, 用于渲染
//
// 关键概念:
//   - 顶点 (Vertex): 3D 模型的基本单元, 包含位置/法向量/UV 等属性
//   - 索引 (Index): 三角形的三个顶点索引, 用于索引绘制
//   - rings/sectors: 球体的经纬度细分, 越多越光滑但顶点越多
// ============================================================================

// 生成球体顶点:
//   - rings: 纬度方向细分 (默认 32)
//   - sectors: 经度方向细分 (默认 64)
//   - 返回: 顶点数组, 包含位置/法向量/UV
//   - 算法: 球坐标 (phi, theta) 转直角坐标 (x, y, z)
std::vector<Vertex> generateSphere(int rings = 32, int sectors = 64);

// 生成球体索引:
//   - rings/sectors: 必须与 generateSphere 的参数一致
//   - 返回: 索引数组, 每三个索引组成一个三角形
//   - 算法: 遍历每个四边形网格, 拆成两个三角形
std::vector<uint32_t> generateSphereIndices(int rings, int sectors);

// 生成地面平面 (用于接收阴影):
//   - size: 平面边长 (默认 10.0)
//   - y: 平面高度 (默认 -1.5, 在球体下方)
//   - 返回: 6 个顶点 (2 个三角形组成的四边形)
//   - 法向量: (0, 1, 0), 朝上
//   - UV: (0,0) 到 (1,1), 可用于贴图
std::vector<Vertex> generatePlane(float size = 10.0f, float y = -1.5f);

// 生成平面索引:
//   - 返回: {0, 1, 2, 3, 4, 5}, 对应 2 个三角形
std::vector<uint32_t> generatePlaneIndices();
